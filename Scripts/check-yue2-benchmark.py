#!/usr/bin/env python3
"""Compare fixed-work native/Python YuE2 outputs and stage timings.

Inputs are generated by benchmark-yue2-native-python.py and the native harness.
This checks numerical fidelity; it does not turn stage timings into an estimated
end-to-end song time. Keep fixtures, timing logs and reports outside the repo.
"""
import argparse
import array
import json
import math
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("directory", type=Path)
parser.add_argument("native_log", type=Path)
parser.add_argument("--require-faster", action="store_true",
                    help="Require native total time <= Python at every replayed step budget")
args = parser.parse_args()
manifest = json.loads((args.directory / "benchmark-manifest.json").read_text())
if args.require_faster and manifest.get("mode") != "pipeline-replay":
    parser.error("--require-faster requires a complete pipeline replay")
python = json.loads((args.directory / "python-timing.json").read_text())
native = [json.loads(line) for line in args.native_log.read_text().splitlines()
          if line.startswith('{"stage":')]
report = {"workload": manifest, "seconds": {}, "outputs": {}}
native_times = {trial["stage"]: trial["seconds"] for trial in native}
for trial in python["trials"]:
    stage, elapsed = trial["stage"], trial["seconds"]
    if stage in native_times:
        report["seconds"][stage] = {
            "python": elapsed, "native": native_times[stage],
            "native_over_python": native_times[stage] / elapsed,
        }

if manifest.get("mode") == "pipeline-replay":
    # Every token and solver step was executed. Excludes initial model/tokenizer
    # loading and sampling; decoding includes decoder loading in both backends.
    report["replayed_compute_seconds"] = {}
    for steps in manifest["steps"]:
        stages = ["plan", "semantic", f"synthesis-{steps}", "decode"]
        totals = {backend: sum(report["seconds"][stage][backend] for stage in stages)
                  for backend in ("python", "native")}
        totals["native_over_python"] = totals["native"] / totals["python"]
        report["replayed_compute_seconds"][str(steps)] = totals
        if args.require_faster:
            assert totals["native"] <= totals["python"], (steps, totals)

for name in [*(f"latent-{steps}" for steps in manifest["steps"]), "audio"]:
    def read(backend):
        values = array.array("f")
        values.frombytes((args.directory / f"{backend}-{name}.bin").read_bytes())
        return values
    reference, actual = read("python"), read("native")
    expected = manifest["frames"] * 64 if name != "audio" else (manifest["frames"] * 1920 - 64) * 2
    assert len(reference) == len(actual) == expected, (name, len(reference), len(actual), expected)
    assert all(math.isfinite(value) for value in reference), name
    assert all(math.isfinite(value) for value in actual), name
    energy = sum(value * value for value in reference)
    assert energy > 0, name
    relative = math.sqrt(sum((a-b)**2 for a, b in zip(reference, actual)) / energy)
    limit = .0001 if name == "audio" else .02
    assert relative < limit, (name, relative, limit)
    report["outputs"][name] = {"elements": expected, "relative_l2": relative, "limit": limit}

print(json.dumps(report, indent=2))
